def seed_doc_land(db, uid: int, level: int, land: dict, nhom_map: dict, stats: dict) -> None:
    exists = db.execute(
        text("SELECT 1 FROM bo_de WHERE loai = 'thua' AND cap_do_id = :c AND ky_nang = 'doc' AND ten = :t LIMIT 1"),
        {"c": level, "t": land["ten"]},
    ).first()
    if exists:
        print(f"· Bỏ qua Đọc HSK {level} · {land['ten']} (đã có)")
        return

    slot_counter = 0

    def create_q(spec: dict) -> int:
        nonlocal slot_counter
        nhom_id = nhom_map.get(spec["nhom"])
        if spec["dang"] == "dung_sai":
            opts = [
                {"noi_dung": "Đúng (对)", "la_dap_an_dung": bool(spec["is_true"])},
                {"noi_dung": "Sai (错)", "la_dap_an_dung": not bool(spec["is_true"])},
            ]
        else:
            shuffled, ans = place(spec["raw_opts"], spec["correct"], slot_counter)
            slot_counter += 1
            opts = mc(shuffled, ans)

        qid = create_question(db, QuestionIn(
            dang=spec["dang"],
            cap_do_id=level,
            ky_nang="doc",
            dung_on_luyen=True,
            dung_thi_thu=False,
            nguon_noi_dung="tu_soan",
            nhom_kien_thuc_id=nhom_id,
            noi_dung=spec["noi_dung"],
            pinyin=spec["pinyin"],
            dich_nghia=spec["dich_nghia"],
            goi_y=spec["goi_y"],
            goi_y_2=spec["goi_y_2"],
            giai_thich=spec["giai_thich"],
            phuong_an=opts,
        ), uid)
        publish_question(db, qid, uid)
        stats["questions"] += 1
        return qid

    lesson_rows = []
    for lname, q_specs in land["bai"]:
        qids = [create_q(s) for s in q_specs]
        lesson_rows.append((lname, qids))

    final_qids = [create_q(s) for s in land["cuoi_thua"]]

    land_id = path_service.create_land(
        db,
        SimpleNamespace(cap_do_id=level, ky_nang="doc", ten=land["ten"], muc_tieu=land["muc_tieu"]),
        uid,
    )
    for pos, (lname, qids) in enumerate(lesson_rows + [("Kiểm tra cuối thửa", final_qids)], start=1):
        lesson_id = path_service.create_lesson(
            db,
            SimpleNamespace(thua_id=land_id, vi_tri=pos, ten=lname, muc_tieu=None, tai_lieu_id=None),
            uid,
        )
        path_service.set_lesson_items(db, lesson_id, [SimpleNamespace(cau_hoi_id=q) for q in qids])
        path_service.lesson_status(db, lesson_id, "dang")
    path_service.land_status(db, land_id, "dang")
    stats["lands"] += 1
    print(f"→ Đã đăng Đọc HSK {level} · {land['ten']} (4 bài + 1 cuối thửa = 30 câu)")


def main() -> int:
    db = SessionLocal()
    stats = {"lands": 0, "questions": 0}
    try:
        uid = db.execute(
            text("SELECT u.id FROM nguoi_dung u JOIN vai_tro v ON v.id = u.vai_tro_id WHERE v.ma = 'giang_vien' ORDER BY u.id DESC LIMIT 1")
        ).scalar_one()
        levels = {m: int(i) for m, i in db.execute(text("SELECT ma, id FROM cap_do")).all()}
        nhom_map = {m: int(i) for m, i in db.execute(text("SELECT ma, id FROM nhom_kien_thuc")).all()}

        for land in HSK2_DOC_LANDS:
            seed_doc_land(db, uid, levels["HSK2"], land, nhom_map, stats)
        for land in HSK3_DOC_LANDS:
            seed_doc_land(db, uid, levels["HSK3"], land, nhom_map, stats)
        for land in HSK4_DOC_LANDS:
            seed_doc_land(db, uid, levels["HSK4"], land, nhom_map, stats)

        print(f"HOÀN TẤT ĐỌC HSK 2–4: +{stats['lands']} thửa, +{stats['questions']} câu ôn luyện đã đăng.")
        return 0
    finally:
        db.close()


